import axios from '../../services/axiosInstance'

export const login = (credentials) => axios.post('/auth/login', credentials)
export const googleAuth = (payload) => axios.post('/auth/google', payload)
export const register = (userData) => axios.post('/auth/register', userData)
export const verifyEmail = (data) => axios.post('/auth/verify-email', data)
export const resendVerificationOTP = (data) => axios.post('/auth/resend-otp', data)
export const forgotPassword = (data) => axios.post('/auth/forgot-password', data)
export const verifyResetOTP = (data) => axios.post('/auth/verify-reset-otp', data)
export const resetPassword = (data) => axios.post('/auth/reset-password', data)
export const verifyAdminTwoFactor = (data) => axios.post('/auth/admin-2fa/verify-login', data)
export const setupAdminTwoFactor = () => axios.post('/auth/admin-2fa/setup')
export const confirmAdminTwoFactor = (data) => axios.post('/auth/admin-2fa/confirm', data)
export const disableAdminTwoFactor = (data) => axios.post('/auth/admin-2fa/disable', data)
export const logout = () => axios.post('/auth/logout')
export const getAllUsers = () => axios.get('/users/all')
